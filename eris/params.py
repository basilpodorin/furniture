"""Параметры кресла ERIS с поворотным механизмом. Все размеры — мм.

Система координат изделия (мировая):
  X — вправо (если смотреть на кресло спереди), 0 — плоскость симметрии;
  Y — назад (фасад кресла в сторону −Y), 0 — ось поворота;
  Z — вверх от пола.
"""

# --------------------------------------------------------------- форма (3D-модель)
# Поверхность обивки берётся из 3D-модели прототипа (Spin.max, SK-00033861),
# сглаженной как TurboSmooth (2 итерации Catmull–Clark).
MODEL_SUBDIV = 2
# Модель в плане ~823×842 мм; по каталогу 800×820 (±30). Масштаб по X/Y
# приводит габарит к каталожному; высота (720) совпадает и не масштабируется.
MODEL_XY_SCALE = 0.975
# Положение оси поворота относительно центра модели по глубине (в мм модели,
# минус — вперёд). Ось чуть впереди центра: сидящий человек смещает центр
# тяжести к фасаду, так кресло устойчивее при посадке на передний край.
MODEL_AXIS_Y = -20.0

# --------------------------------------------------------------- неподвижное основание
PAD_H = 4            # фетровые/полиуретановые накладки под диском
DISC_D = 600         # стальной диск-основание Ø600 × 6 (≈13.3 кг — противовес)
DISC_T = 6
DISC_PAD_R = 285     # радиус окружности накладок (8 шт.)
DISC_PADS = 8

# Поворотный механизм 195×195, высота 25 мм (Яндекс Маркет, арт. 5583855927).
# ВНИМАНИЕ: шаг и диаметр крепёжных отверстий на странице товара не указаны —
# значения ниже типовые для площадок 195 мм; перед заказом ЧПУ замерить механизм.
SWIVEL_SIZE = 195
SWIVEL_H = 25
SWIVEL_HOLE_PITCH = 170   # расстояние между центрами отверстий (квадрат)
SWIVEL_HOLE_D = 7
ACCESS_HOLE_D = 32        # технологическое отверстие в диске для закручивания винтов

# --------------------------------------------------------------- материалы каркаса
PLY = 18             # фанера берёзовая ФК 18 мм — несущие детали (плиты, перегородки)
PLY_RIB = 15         # фанера ФК 15 мм — рёбра-лекала (вспомогательные, как принято в ЧПУ-каркасах)
PLY_RHO = 680        # кг/м³
SKIN_T = 4           # полосы/обшивка: гибкая фанера 4 мм (или ДВП 3.2)
TOOL_D = 6           # фреза ЧПУ, мм (для «собачьих косточек» в пазах)
FIT = 0.3            # зазор в пазах под шипы

# --------------------------------------------------------------- высоты (Z, от пола)
Z_BODY_BOTTOM = PAD_H + DISC_T + SWIVEL_H - 2   # низ обивки корпуса (ткань под дном)
Z_P1 = PAD_H + DISC_T + SWIVEL_H                # низ дна П1 = верх механизма = 35
Z_P3 = 304           # низ плиты уровня сиденья П3 (верх 322 — под кантом сиденья)
Z_P4 = 610           # низ верхнего шаблона П4 (верх 628; сверху мягкий валик ≈100)
Z_SEAT_BACK = 298    # верх задней перегородки = задний край ремней сиденья

# --------------------------------------------------------------- толщины обивки
OUT_OFFSET = 50      # от поверхности обивки до кромки каркаса снаружи
                     # (ППУ 40 + синтепон/ткань ≈6 + полосы 4)
TOP_OFFSET = 90      # сверху подлокотников и спинки (валик)
BOTTOM_MARGIN = 22   # вылет обивки за кромку дна П1

# --------------------------------------------------------------- внутренняя полость
ARM_SKIN_X = 272     # полуширина полости спинки (внутренняя кромка П4 у подлокотника, ремни)
BACK_BELT_Y0 = 250   # линия ремней спинки внизу (верх П3, z=322)
BACK_BELT_Y1 = 285   # линия ремней спинки вверху (кромка П4, z=628)
BACK_BELT_GAP = 35   # зазор ремни–рёбра внизу (к верху сходит на 5 мм)
CAVITY_R = 60        # радиус скругления углов полости в плане
SEAT_OPEN_X = 240    # полуширина проёма сиденья в П3 (полка П3 до боковины ≈42 мм)
SEAT_OPEN_BACK = 212 # задняя кромка проёма П3
BACK_PART_Y = 181    # передняя грань задней перегородки (ремни сиденья)
FRONT_RAIL_W = 85    # ширина передней царги (часть П3)

# --------------------------------------------------------------- боковины
# Боковина Б — одно цельное лекало на сторону посередине толщины подлокотника:
# от низа корпуса до П4, от торца до угла спинки. Она же — боковая стенка короба сиденья
# (в неё входят шипы ПГ2, ПГ3 и П3). Поролон с обеих сторон.
